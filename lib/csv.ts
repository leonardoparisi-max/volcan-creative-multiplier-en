// ---------------------------------------------------------------------------
// Minimal, correct CSV parse/serialize (RFC-4180-ish): handles quoted fields,
// embedded commas, quotes, and newlines. No external dependency.
// ---------------------------------------------------------------------------

export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let field = "";
  let row: string[] = [];
  let inQuotes = false;
  let i = 0;
  const s = text.replace(/\r\n/g, "\n").replace(/\r/g, "\n");

  while (i < s.length) {
    const c = s[i];
    if (inQuotes) {
      if (c === '"') {
        if (s[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
        i++;
        continue;
      }
      field += c;
      i++;
      continue;
    }
    if (c === '"') {
      inQuotes = true;
      i++;
      continue;
    }
    if (c === ",") {
      row.push(field);
      field = "";
      i++;
      continue;
    }
    if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
      i++;
      continue;
    }
    field += c;
    i++;
  }
  // flush trailing field/row
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => !(r.length === 1 && r[0] === ""));
}

function escapeField(v: string): string {
  if (v == null) return "";
  const needs = /[",\n]/.test(v);
  const e = v.replace(/"/g, '""');
  return needs ? `"${e}"` : e;
}

export function serializeCsv(rows: string[][]): string {
  return rows.map((r) => r.map(escapeField).join(",")).join("\n") + "\n";
}
